const viewNames = {
  general: "navGeneral",
  "sobre-mi": "navAbout",
  habilidades: "navSkills",
  proyectos: "navProjects",
  intereses: "navInterests"
};

const navButtons = [...document.querySelectorAll(".nav-link")];
const views = [...document.querySelectorAll(".view")];
const currentSection = document.querySelector("#current-section");
const languageButton = document.querySelector("#language-toggle");
const themeButton = document.querySelector("#theme-toggle");
let language = "es";
const originalText = new Map(
  [...document.querySelectorAll("[data-i18n]")].map((element) => [element, element.innerHTML])
);

function showView(viewId) {
  const view = document.getElementById(viewId);
  if (!view || !viewNames[viewId]) return;

  views.forEach((section) => {
    const active = section === view;
    section.hidden = !active;
    section.classList.toggle("active", active);
  });

  navButtons.forEach((button) => {
    const active = button.dataset.view === viewId;
    button.classList.toggle("active", active);
    if (active) button.setAttribute("aria-current", "page");
    else button.removeAttribute("aria-current");
  });

  currentSection.dataset.i18n = viewNames[viewId];
  currentSection.textContent = translations[language][viewNames[viewId]] || translations.es[viewNames[viewId]] || document.querySelector(`[data-i18n="${viewNames[viewId]}"]`)?.textContent;
  document.title = `Diego Martínez Martínez — ${currentSection.textContent}`;
  if (window.matchMedia("(max-width: 780px)").matches) window.scrollTo({ top: 0, behavior: "smooth" });
}

function setLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translated = translations[language][key];
    if (language === "es") element.innerHTML = originalText.get(element);
    else if (translated) element.innerHTML = translated;
  });
  languageButton.textContent = language === "es" ? "EN" : "ES";
  languageButton.lang = language === "es" ? "en" : "es";
  languageButton.setAttribute("aria-label", language === "es" ? "Switch to English" : "Cambiar a español");
  const isDark = document.body.dataset.theme === "dark";
  themeButton.setAttribute(
    "aria-label",
    language === "es"
      ? isDark ? "Cambiar al tema claro" : "Cambiar al tema oscuro"
      : isDark ? translations.en.themeSwitchLight : translations.en.themeSwitchDark
  );
  const activeView = document.querySelector(".view.active");
  if (activeView) showView(activeView.id);
}

navButtons.forEach((button) => button.addEventListener("click", () => showView(button.dataset.view)));
document.querySelectorAll("[data-go]").forEach((button) => button.addEventListener("click", () => showView(button.dataset.go)));
document.querySelector(".brand").addEventListener("click", (event) => {
  event.preventDefault();
  showView("general");
});
languageButton.addEventListener("click", () => setLanguage(language === "es" ? "en" : "es"));
themeButton.addEventListener("click", () => {
  const dark = document.body.dataset.theme !== "dark";
  document.body.dataset.theme = dark ? "dark" : "light";
  themeButton.setAttribute("aria-checked", String(dark));
  themeButton.setAttribute(
    "aria-label",
    language === "es"
      ? dark ? "Cambiar al tema claro" : "Cambiar al tema oscuro"
      : dark ? translations.en.themeSwitchLight : translations.en.themeSwitchDark
  );
});

showView("general");
